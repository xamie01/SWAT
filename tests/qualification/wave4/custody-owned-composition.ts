export const custodyOwnedBoundary = Object.freeze({ sourceImplemented: true, runtimeAccepted: false,
  liveCapabilityAccepted: false, productionReady: false } as const);
/** Implementation is callable but these canonical source backings are not
 * supplied by an identity label, callback fixture or the public coordinator. */
export const custodyOwnedSourceGaps = Object.freeze([
  'protected persisted execution-reader and observer capability lookup/provisioning remains absent',
  'approved deployed wrap/unwrap identity validation and authenticated receipt adapter must be supplied',
  'independent deployed-policy decoder and atomic remote nonce/effect executor must be supplied',
  'owned custody lifecycle SQL remains separate from ambient execution-grants replacement/revoke bodies (strict audit insert is shared)'
] as const);
export type CustodyCapability = 'wrap-only' | 'secret-admission' | 'grant-enrollment' | 'execution-secret-read'
  | 'execution-unwrap' | 'grant-lifecycle' | 'deployed-inspection' | 'scoped-execution';
export interface CustodyCapabilityRequest {
  readonly capability: CustodyCapability; readonly identity: string;
  readonly userId: string; readonly grantId: string; readonly deploymentId: string;
  readonly chain: CustodySecretBinding['chain']; readonly chainId: string;
  readonly payloadDigest: string;
}
/** Must independently verify actual approved identity + least privilege and exact
 * scope. This callback is a mandatory evidence authority, NOT a name-to-permission
 * registration. Missing deployed identities return null; clients confer nothing. */
export interface CustodyCapabilityAdmission {
  authorize(request: CustodyCapabilityRequest): Promise<{
    readonly request: CustodyCapabilityRequest; readonly approved: true;
    readonly validUntil: Date; readonly capabilities: readonly CustodyCapability[];
  } | null>;
}
export interface CustodyCheckedTransaction {
  <T>(scope: UserScope, action: (client: PoolClient) => Promise<T>): Promise<{
    readonly value: T; readonly outcome: 'committed';
  }>;
}
export interface CustodyOwnedDatabasePort {
  readonly identity: string;
  /** Bounded owned transaction pins direct session/current_user, tenant on one
   * client. It must not return committed on rollback, cancellation, timeout or
   * uncertain COMMIT. Connection/reset/drain ownership remains with coordinator. */
  readonly transaction: CustodyCheckedTransaction;
}
export interface CustodyAuthenticatedWrapPort extends CustodyEnrollmentWrapPort {
  readonly serviceIdentity: string;
  /** Independently authenticated receipt for this exact sealed record, not a
   * token generated by the enrolling application. */
  attest(input: { readonly record: CustodyEnrollmentRecord; readonly userId: string;
    readonly payloadDigest: string }): Promise<CustodyAdmissionAuthentication>;
}
export interface CustodyOwnedCompositionPorts {
  readonly deploymentId: string;
  readonly chainIds: Readonly<Partial<Record<CustodySecretBinding['chain'], string>>>;
  readonly now: () => Date;
  readonly check: () => void;
  readonly allocateGrantId: () => Promise<string>;
  readonly admissions: CustodyCapabilityAdmission;
  readonly wrap: CustodyAuthenticatedWrapPort;
  readonly unwrap: CustodyExecutionUnwrapPort & { readonly serviceIdentity: string };
  readonly admissionVerifier: CustodyAdmissionVerifier;
  readonly database: {
    readonly admission: CustodyOwnedDatabasePort;
    readonly enrollment: CustodyOwnedDatabasePort;
    readonly execution: CustodyOwnedDatabasePort;
    readonly lifecycle: CustodyOwnedDatabasePort;
  };
  readonly delegation: {
    readonly identity: string;
    readonly policy: DeployedDelegationPolicy;
    readonly maxVerificationAgeMs: number;
    readonly inspect: DeployedDelegationPorts['inspect'];
    readonly decode: DeployedDelegationPorts['decode'];
    /** MUST atomically validate actual deployed revision/nonce/payload/deadline
     * and consume authorization at the actual effect boundary. The caller DB
     * row lock is only local lifecycle protection. No unrestricted signer port. */
    readonly executeScoped: (client: PoolClient, secret: Uint8Array,
      input: Parameters<DeployedDelegationPorts['signScoped']>[0]) => Promise<AuthoritySigningResult>;
  };
}
function requireValue(value: unknown): asserts value {
  if (!value) throw new CustodyContractError('custody-unavailable');
}
function fingerprint(grant: DelegationGrant): string {
  return custodyPolicyDigest({ id: grant.id, userId: grant.userId, chain: grant.chain,
    grantKind: grant.grantKind, accountAddress: grant.accountAddress, status: grant.status,
    lifecycleRevision: grant.lifecycleRevision, revocationTombstone: grant.revocationTombstone?.toISOString() ?? null,
    revokedAt: grant.revokedAt?.toISOString() ?? null, expiresAt: grant.expiresAt?.toISOString() ?? null });
}
/** Callable private composition using the canonical production bodies, never an
 * ambient pool or a qualification-only enrollment/execution implementation. */
export function createOwnedCustodyComposition(ports: CustodyOwnedCompositionPorts) {
  requireValue(ports && typeof ports.now === 'function' && typeof ports.check === 'function' &&
    typeof ports.allocateGrantId === 'function' && typeof ports.admissions?.authorize === 'function' &&
    typeof ports.wrap?.seal === 'function' && typeof ports.wrap.attest === 'function' && typeof ports.unwrap?.open === 'function' &&
    typeof ports.admissionVerifier?.verify === 'function' && typeof ports.delegation?.inspect === 'function' &&
    typeof ports.delegation.decode === 'function' && typeof ports.delegation.executeScoped === 'function');
  const deploymentId = ports.deploymentId, chainIds = { ...ports.chainIds }, now = ports.now, check = ports.check,
    admissions = ports.admissions, wrapProvider = ports.wrap, unwrapProvider = ports.unwrap, databases = { ...ports.database },
    delegation = { ...ports.delegation, policy: structuredClone(ports.delegation.policy) };
  custodyIdentifier(deploymentId);
  const identities = [wrapProvider.serviceIdentity, unwrapProvider.serviceIdentity, databases.admission?.identity,
    databases.enrollment?.identity, databases.execution?.identity, delegation.identity];
  requireValue(identities.every(identity => typeof identity === 'string' && identity.length > 0) &&
    new Set(identities).size === identities.length && databases.admission.identity === 'swat_custody_writer' &&
    databases.enrollment.identity === 'swat_app' && databases.lifecycle?.identity === 'swat_app' &&
    databases.execution.identity !== 'swat_app' && databases.execution.identity !== 'swat_custody_writer');
  for (const database of Object.values(databases)) requireValue(typeof database.transaction === 'function');
  async function admitted(capability: CustodyCapability, identity: string, userId: string, grantId: string,
    chain: CustodySecretBinding['chain'], payloadDigest: string) {
    check();
    const request: CustodyCapabilityRequest = { capability, identity, userId, grantId, chain,
      deploymentId, chainId: chainIds[chain] ?? '', payloadDigest };
    const admission = structuredClone(await admissions.authorize({ ...request }));
    check();
    // Exact privilege sets: enrollment/wrap cannot carry read/unwrap/effect
    // permission. Execution read also cannot mint admissions or enroll grants.
    const allowed: readonly CustodyCapability[] = capability === 'wrap-only' ? ['wrap-only'] :
      capability === 'secret-admission' ? ['secret-admission'] :
      capability === 'grant-enrollment' || capability === 'grant-lifecycle' ? ['grant-enrollment','grant-lifecycle'] :
      capability === 'execution-secret-read' || (capability === 'scoped-execution' && identity === databases.execution.identity)
        ? ['execution-secret-read','scoped-execution'] :
      capability === 'execution-unwrap' ? ['execution-unwrap'] : ['deployed-inspection','scoped-execution'];
    requireValue(admission?.approved === true && custodyPolicyDigest(admission.request) === custodyPolicyDigest(request) &&
      admission.validUntil instanceof Date && admission.validUntil.getTime() > now().getTime() &&
      admission.capabilities.includes(capability) && new Set(admission.capabilities).size === admission.capabilities.length &&
      admission.capabilities.every(power => allowed.includes(power)));
  }
  async function db<T>(port: CustodyOwnedDatabasePort, scope: UserScope, grantId: string,
    chain: CustodySecretBinding['chain'], digest: string, capability: CustodyCapability,
    action: (client: PoolClient) => Promise<T>): Promise<T> {
    const userId = scope.userId;
    await admitted(capability, port.identity, userId, grantId, chain, digest);
    let result: Awaited<ReturnType<CustodyCheckedTransaction>>;
    try {
      result = await port.transaction({ userId } as UserScope, async client => {
      check();
      const observed = await client.query<{ authenticated_role: string; runtime_role: string; tenant: string | null; bypass: string | null }>(
        `SELECT session_user AS authenticated_role,current_user AS runtime_role,
          current_setting('app.current_user_id',true) AS tenant,current_setting('app.bypass_rls',true) AS bypass`);
      const row = observed.rows[0];
      requireValue(observed.rows.length === 1 && row?.authenticated_role === port.identity && row.runtime_role === port.identity &&
        row.tenant === userId && row.bypass === 'off');
      await admitted(capability, port.identity, userId, grantId, chain, digest);
      const value = await action(client); check(); return value;
      });
    } catch (error) {
      if (error instanceof CustodyContractError) throw error;
      throw new CustodyContractError('custody-unavailable');
    }
    check(); requireValue(result?.outcome === 'committed'); return result.value as T;
  }
  async function load(scope: UserScope, grantId: string, chain: CustodySecretBinding['chain']) {
    const digest = custodyPolicyDigest({ userId: scope.userId, grantId, chain });
    return db(databases.execution, scope, grantId, chain, digest, 'execution-secret-read', async client => {
      const grant = await createCustodyExecutionStore(async (_scope, action) => action(client as CustodySqlClient)).load(scope, grantId);
      if (!grant) return null;
      requireValue(grant.chain === chain && grant.secretBinding && grant.sealedSecret && grant.keyVersion !== null);
      const admission = await loadCustodySecretAdmissionWithClient(client as CustodySqlClient, scope, grantId, grant.keyVersion!);
      requireCustodySecretAdmission(admission, scope.userId, grant);
      requireValue(admission.acceptedAt.getTime() <= now().getTime() &&
        (!grant.revocationTombstone || admission.acceptedAt > grant.revocationTombstone));
      return grant;
    });
  }
  const wrap: CustodyEnrollmentWrapPort = { wrapperId: wrapProvider.wrapperId, keyVersion: wrapProvider.keyVersion,
    async seal({ plaintext, binding }) {
      await admitted('wrap-only', wrapProvider.serviceIdentity, binding.userId, binding.grantId, binding.chain, custodyPolicyDigest(binding));
      // Authenticate complete canonical context before delegating any plaintext.
      custodyEnvelopeContext(binding); check();
      const sealed = await wrapProvider.seal({ plaintext, binding }); check(); return sealed;
    } };
  const enrollment = createCustodyEnrollment({ deploymentId, chainIds, now, allocateGrantId: ports.allocateGrantId, wrap,
    store: { async record(scope, record) {
      requireValue(record.secretBinding && record.sealedSecret && record.keyVersion !== null); // keyed custody composition only
      const digest = custodyAdmissionPayloadDigest(scope.userId, record);
      await admitted('wrap-only', wrapProvider.serviceIdentity, scope.userId, record.id, record.chain, digest);
      const authentication = await wrapProvider.attest({ record: structuredClone(record), userId: scope.userId, payloadDigest: digest });
      check(); requireValue(authentication.wrapperId === wrap.wrapperId && authentication.serviceIdentity === wrapProvider.serviceIdentity);
      const prepare = prepareCustodySecretAdmission({ scope, record, authentication, verifier: ports.admissionVerifier, now });
      // Admission uses its OWN direct writer and checked COMMIT. An app rollback
      // retains this immutable receipt; there is deliberately no deletion trick.
      await db(databases.admission, scope, record.id, record.chain, digest, 'secret-admission', client => prepare(client as CustodySqlClient));
      return db(databases.enrollment, scope, record.id, record.chain, digest, 'grant-enrollment', async client => {
        const admission = await loadCustodySecretAdmissionWithClient(client as CustodySqlClient, scope, record.id, record.keyVersion!);
        requireCustodySecretAdmission(admission, scope.userId, record, authentication);
        return createCustodyEnrollmentStore(async (_scope, action) => action(client as CustodySqlClient)).record(scope, record);
      });
    } } });
  function execution(scope: UserScope, grantId: string, chain: CustodySecretBinding['chain']) {
    const pinnedScope = { userId: scope.userId } as UserScope;
    return createCustodyExecutionAccess({ deploymentId, chainIds, now, store: { load: (s, id) => load(s, id, chain) },
      unwrap: { async open({ sealedSecret, binding }) {
        requireValue(binding.userId === pinnedScope.userId && binding.grantId === grantId && binding.chain === chain);
        await admitted('execution-unwrap', unwrapProvider.serviceIdentity, binding.userId, binding.grantId, chain,
          custodyPolicyDigest({ sealedSecret, binding }));
        custodyEnvelopeContext(binding); check();
        const bytes = await unwrapProvider.open({ sealedSecret, binding });
        try { check(); return bytes; } catch (error) { bytes?.fill(0); throw error; }
      } } });
  }
  function authority(scope: UserScope, grantId: string) {
    const userId = scope.userId, chain = 'robinhood-chain' as const;
    const loadGrant: DeployedDelegationPorts['loadGrant'] = async (requestedUser, requestedChain) => {
      if (requestedUser !== userId || requestedChain !== chain) return null;
      const grant = await load({ userId } as UserScope, grantId, chain);
      if (!grant || (grant.grantKind !== 'eip7702' && grant.grantKind !== 'session_key_4337')) return null;
      return { id: grant.id, userId, chain, grantKind: grant.grantKind, accountAddress: grant.accountAddress,
        status: grant.status, lifecycleRevision: grant.lifecycleRevision, revocationTombstone: grant.revocationTombstone,
        revokedAt: grant.revokedAt, expiresAt: grant.expiresAt };
    };
    return createDeployedDelegationAuthority({ id: 'wave4-owned-custody', chain, deploymentId, chainId: chainIds[chain] ?? '',
      ...delegation.policy, maxVerificationAgeMs: delegation.maxVerificationAgeMs, now,
      ports: { loadGrant, inspect: async grant => {
        await admitted('deployed-inspection', delegation.identity, userId, grantId, chain, fingerprint(grant));
        const inspected = await delegation.inspect(grant); check(); return inspected;
      }, decode: delegation.decode, signScoped: async input => {
        const session = await execution({ userId } as UserScope, grantId, chain).session({ userId } as UserScope, grantId);
        return session.use((secret, boundary) => db(databases.execution, { userId } as UserScope, grantId, chain,
          custodyPolicyDigest({ grant: fingerprint(input.grant), effect: input.effect, payloadScope: input.payloadScope }),
          'scoped-execution', async client => {
            const current = await lockCustodyGrantWithClient(client as CustodySqlClient, { userId } as UserScope, grantId);
            assertCustodyActive(current, now());
            requireValue(current.lifecycleRevision === input.expectedLifecycleRevision && boundary.lifecycleRevision === input.expectedLifecycleRevision &&
              current.revocationTombstone?.getTime() === input.expectedRevocationTombstone?.getTime() &&
              current.expiresAt?.getTime() === input.grant.expiresAt?.getTime() && fingerprint(current as DelegationGrant) === fingerprint(input.grant) &&
              now().getTime() < input.issuedDeadline.getTime());
            await admitted('scoped-execution', delegation.identity, userId, grantId, chain,
              custodyPolicyDigest({ effect: input.effect, payloadScope: input.payloadScope, lifecycleRevision: current.lifecycleRevision }));
            check(); return delegation.executeScoped(client, secret, input);
          }));
      } } });
  }
  return {
    boundary: custodyOwnedBoundary,
    enroll: (scope: UserScope, input: CustodyEnrollmentInput) => enrollment.enroll(scope, input),
    /** Raw single-use secret session is internal scoped executor input, not public authority. */
    session: (scope: UserScope, grantId: string, chain: CustodySecretBinding['chain']) => execution(scope, grantId, chain).session(scope, grantId),
    authority,
    transition(scope: UserScope, input: Parameters<typeof transitionCustodyGrantWithClient>[2] & { readonly chain: CustodySecretBinding['chain'] }) {
      const captured = structuredClone(input), s = { userId: scope.userId } as UserScope;
      return db(databases.lifecycle, s, captured.grantId, captured.chain,
        custodyPolicyDigest({ ...captured, now: captured.now.toISOString() }), 'grant-lifecycle',
        client => transitionCustodyGrantWithClient(client as CustodySqlClient, s, captured));
    },
    /** New record must already have a independently committed secret admission. */
    replace(scope: UserScope, input: Parameters<typeof replaceCustodyGrantWithClient>[2]) {
      const captured = structuredClone(input), s = { userId: scope.userId } as UserScope;
      return db(databases.lifecycle, s, captured.record.id, captured.record.chain, custodyAdmissionPayloadDigest(s.userId, captured.record),
        'grant-lifecycle', client => replaceCustodyGrantWithClient(client as CustodySqlClient, s, captured));
    },
    admitReplacement(scope: UserScope, record: CustodyEnrollmentRecord, authentication: CustodyAdmissionAuthentication): Promise<CustodySecretAdmission> {
      const s = { userId: scope.userId } as UserScope, captured = structuredClone(record);
      const prepare = prepareCustodySecretAdmission({ scope: s, record: captured, authentication: { ...authentication }, verifier: ports.admissionVerifier, now });
      return db(databases.admission, s, captured.id, captured.chain, custodyAdmissionPayloadDigest(s.userId, captured), 'secret-admission',
        client => prepare(client as CustodySqlClient));
    }
  };
}
export type OwnedCustodyComposition = ReturnType<typeof createOwnedCustodyComposition>;
