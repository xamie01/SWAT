import { Server } from "@modelcontextprotocol/sdk/server/index.js";
import { SSEServerTransport } from "@modelcontextprotocol/sdk/server/sse.js";
import {
  CallToolRequestSchema,
  ListToolsRequestSchema,
} from "@modelcontextprotocol/sdk/types.js";
import express from "express";
import { Redis } from "ioredis";
import { query } from "@swat/db";
import { initLogger, REDIS_CHANNELS } from "@swat/shared";
import { z } from "zod";

initLogger("mcp-server");

const PORT = Number(process.env.MCP_PORT ?? 3005);
const redisUrl = process.env.REDIS_URL ?? "redis://localhost:6379";
const redis = new Redis(redisUrl, { maxRetriesPerRequest: null });

// Initialize MCP Server
const server = new Server(
  {
    name: "swat-mcp-server",
    version: "0.1.0",
  },
  {
    capabilities: {
      tools: {},
    },
  }
);

// Define tools
const TOOL_DEFINITIONS = [
  {
    name: "get_recent_signals",
    description: "Fetch the most recent trading signals generated by the SWAT engine.",
    inputSchema: {
      type: "object",
      properties: {
        limit: {
          type: "number",
          description: "Maximum number of signals to return (default 10).",
        },
      },
    },
  },
  {
    name: "get_wallet_score",
    description: "Retrieve risk scoring, tier, confidence, and statistics for a given Solana wallet address.",
    inputSchema: {
      type: "object",
      properties: {
        walletAddress: {
          type: "string",
          description: "The Solana public key of the wallet to inspect.",
        },
      },
      required: ["walletAddress"],
    },
  },
  {
    name: "get_performance",
    description: "Fetch overall trading performance statistics (win rate, net USD P&L, open positions, recent execution fills).",
    inputSchema: {
      type: "object",
      properties: {},
    },
  },
  {
    name: "get_blacklist",
    description: "Retrieve the list of currently blacklisted token mint addresses.",
    inputSchema: {
      type: "object",
      properties: {},
    },
  },
  {
    name: "add_to_blacklist",
    description: "Add a new token mint address (e.g. stablecoins, spam tokens) to the blacklist config.",
    inputSchema: {
      type: "object",
      properties: {
        tokenMint: {
          type: "string",
          description: "The Solana mint address of the token to blacklist.",
        },
      },
      required: ["tokenMint"],
    },
  },
  {
    name: "remove_from_blacklist",
    description: "Remove a token mint address from the blacklist config.",
    inputSchema: {
      type: "object",
      properties: {
        tokenMint: {
          type: "string",
          description: "The Solana mint address of the token to remove.",
        },
      },
      required: ["tokenMint"],
    },
  },
  {
    name: "trigger_scorer",
    description: "Trigger an on-demand scorer batch run to recalculate wallet tiers, average ROI, and clusters.",
    inputSchema: {
      type: "object",
      properties: {},
    },
  },
];

// Register list tools handler
server.setRequestHandler(ListToolsRequestSchema, async () => {
  return {
    tools: TOOL_DEFINITIONS,
  };
});

// Register call tool handler
server.setRequestHandler(CallToolRequestSchema, async (request) => {
  const { name, arguments: args } = request.params;

  try {
    switch (name) {
      case "get_recent_signals": {
        const limit = Number(args?.limit ?? 10);
        const rows = await query(
          `SELECT id, pattern_type, cluster_id, token_mint, token_name, token_symbol, confidence, signal_score, status, created_at
           FROM signals
           ORDER BY created_at DESC
           LIMIT $1`,
          [limit]
        );
        return {
          content: [{ type: "text", text: JSON.stringify(rows, null, 2) }],
        };
      }

      case "get_wallet_score": {
        const { walletAddress } = z
          .object({ walletAddress: z.string() })
          .parse(args);

        // Fetch wallet details from scoring tables
        const walletRows = await query(
          `SELECT w.address, w.tier, w.composite_score, w.confidence, w.avg_realized_roi, w.total_trades, w.win_rate
           FROM wallets w
           WHERE w.address = $1`,
          [walletAddress]
        );

        if (walletRows.length === 0) {
          return {
            content: [{ type: "text", text: `Wallet ${walletAddress} has not been scored or indexed yet.` }],
          };
        }

        const clusterRows = await query(
          `SELECT c.id, c.name, c.avg_composite_score, c.avg_win_rate
           FROM wallet_clusters c
           JOIN cluster_memberships m ON c.id = m.cluster_id
           WHERE m.wallet_address = $1`,
          [walletAddress]
        );

        return {
          content: [
            {
              type: "text",
              text: JSON.stringify(
                {
                  wallet: walletRows[0],
                  clusters: clusterRows,
                },
                null,
                2
              ),
            },
          ],
        };
      }

      case "get_performance": {
        // Net P&L & Win Rate
        const summaryRows = await query<{
          net_pnl_usd: string | null;
          win_rate: string | null;
          total_trades: string | null;
        }>(`
          SELECT
            SUM(pnl_usd) AS net_pnl_usd,
            CASE WHEN COUNT(*) > 0 THEN (COUNT(*) FILTER (WHERE pnl_usd > 0) * 100.0 / COUNT(*)) ELSE 0 END AS win_rate,
            COUNT(*) AS total_trades
          FROM signals
          WHERE status = 'executed' AND pnl_usd IS NOT NULL
        `);

        // Open positions
        const openRows = await query(`
          SELECT token_mint, token_name, token_symbol, direction, entry_price_usd, cost_basis_usd, created_at
          FROM signals
          WHERE status = 'executed' AND pnl_usd IS NULL
          ORDER BY created_at DESC
        `);

        // Executed fills
        const fillRows = await query(`
          SELECT id, token_mint, direction, amount_sol, amount_usd, token_amount, price_usd, executor, status, created_at
          FROM trades
          ORDER BY created_at DESC
          LIMIT 20
        `);

        return {
          content: [
            {
              type: "text",
              text: JSON.stringify(
                {
                  summary: summaryRows[0] || { net_pnl_usd: 0, win_rate: 0, total_trades: 0 },
                  openPositions: openRows,
                  recentFills: fillRows,
                },
                null,
                2
              ),
            },
          ],
        };
      }

      case "get_blacklist": {
        const rows = await query(`SELECT value FROM config WHERE key = 'blacklist'`);
        const value = rows[0]?.value;
        let blacklist: string[] = [];
        if (value) {
          if (Array.isArray(value)) {
            blacklist = value;
          } else if (typeof value === "string") {
            try {
              const parsed = JSON.parse(value);
              blacklist = Array.isArray(parsed) ? parsed : [parsed];
            } catch {
              blacklist = value.split(",").map((s) => s.trim());
            }
          }
        }
        return {
          content: [{ type: "text", text: JSON.stringify({ blacklist }, null, 2) }],
        };
      }

      case "add_to_blacklist": {
        const { tokenMint } = z.object({ tokenMint: z.string() }).parse(args);

        const rows = await query(`SELECT value FROM config WHERE key = 'blacklist'`);
        const value = rows[0]?.value;
        let blacklist: string[] = [];
        if (value) {
          if (Array.isArray(value)) {
            blacklist = value;
          } else if (typeof value === "string") {
            try {
              const parsed = JSON.parse(value);
              blacklist = Array.isArray(parsed) ? parsed : [parsed];
            } catch {
              blacklist = value.split(",").map((s) => s.trim());
            }
          }
        }

        if (!blacklist.includes(tokenMint)) {
          blacklist.push(tokenMint);
        }

        await query(
          `INSERT INTO config (key, value) VALUES ('blacklist', $1)
           ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = NOW()`,
          [JSON.stringify(blacklist)]
        );

        return {
          content: [{ type: "text", text: `Successfully added ${tokenMint} to the blacklist.` }],
        };
      }

      case "remove_from_blacklist": {
        const { tokenMint } = z.object({ tokenMint: z.string() }).parse(args);

        const rows = await query(`SELECT value FROM config WHERE key = 'blacklist'`);
        const value = rows[0]?.value;
        let blacklist: string[] = [];
        if (value) {
          if (Array.isArray(value)) {
            blacklist = value;
          } else if (typeof value === "string") {
            try {
              const parsed = JSON.parse(value);
              blacklist = Array.isArray(parsed) ? parsed : [parsed];
            } catch {
              blacklist = value.split(",").map((s) => s.trim());
            }
          }
        }

        blacklist = blacklist.filter((mint) => mint !== tokenMint);

        await query(
          `INSERT INTO config (key, value) VALUES ('blacklist', $1)
           ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = NOW()`,
          [JSON.stringify(blacklist)]
        );

        return {
          content: [{ type: "text", text: `Successfully removed ${tokenMint} from the blacklist.` }],
        };
      }

      case "trigger_scorer": {
        await redis.publish(REDIS_CHANNELS.scorerRun, JSON.stringify({}));
        return {
          content: [{ type: "text", text: "Successfully published scorer run command to Redis channel." }],
        };
      }

      default:
        throw new Error(`Unknown tool: ${name}`);
    }
  } catch (error: any) {
    console.error(`[mcp-server] Error executing tool ${name}:`, error);
    return {
      isError: true,
      content: [{ type: "text", text: `Error: ${error.message || error}` }],
    };
  }
});

// Setup Express server with SSE Transport
const app = express();
let transport: SSEServerTransport | null = null;

app.get("/sse", async (req, res) => {
  console.log("[mcp-server] New SSE client connected");
  transport = new SSEServerTransport("/messages", res);
  await server.connect(transport);
});

app.post("/messages", async (req, res) => {
  console.log("[mcp-server] Received POST message");
  if (transport) {
    await transport.handlePostMessage(req, res);
  } else {
    res.status(400).send("No active SSE transport connection");
  }
});

app.listen(PORT, "0.0.0.0", () => {
  console.log(`[mcp-server] SWAT A2MCP Server running at http://0.0.0.0:${PORT}`);
  console.log(`[mcp-server] SSE Endpoint: http://localhost:${PORT}/sse`);
  console.log(`[mcp-server] Messages Endpoint: http://localhost:${PORT}/messages`);
});
